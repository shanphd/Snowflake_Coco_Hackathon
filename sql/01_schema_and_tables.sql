    DECIDED_BY          VARCHAR(100),
    DECIDED_AT          TIMESTAMP_NTZ,
    OUTCOME             VARCHAR(50),
    OUTCOME_DATE        TIMESTAMP_NTZ,
    NOTES               VARCHAR(2000),
    CREATED_AT          TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (LOG_ID)
);

-- 15. CUSTOMER_AI_ENRICHMENT
CREATE OR REPLACE TABLE CUSTOMER_AI_ENRICHMENT (
